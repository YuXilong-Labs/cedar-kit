#!/usr/bin/env python3
# Created by yuxilong on 2026/10/16.
"""Detect upstream releases and build a verified CocoaPods distribution on macOS."""

import argparse
import json
import os
from pathlib import Path
import plistlib
import posixpath
import re
import stat
import subprocess
import zipfile

from patch import patch_binary, require, sha256, verify_binary

BASE = Path(__file__).resolve().parents[1]
BUILD = BASE / "build"
ASSET = "LookInsideServer.xcframework.zip"


def run(*args, **kwargs):
    return subprocess.check_output(args, text=True, **kwargs).strip()


def api(path):
    return json.loads(run("gh", "api", path))


def release_version(upstream_tag, revision):
    require(
        re.fullmatch(r"v?\d+\.\d+\.\d+", upstream_tag) is not None,
        "Only stable x.y.z upstream tags are supported",
    )
    require(
        type(revision) is int and revision > 0,
        "patch_revision must be a positive integer",
    )
    return f"{upstream_tag.removeprefix('v')}-local.{revision}"


def detect(config):
    BUILD.mkdir(exist_ok=True)
    upstream = api(f"repos/{config['upstream']}/releases/latest")
    require(
        not upstream["draft"] and not upstream["prerelease"],
        "Expected a stable release",
    )
    version = release_version(upstream["tag_name"], config["patch_revision"])
    assets = [asset for asset in upstream["assets"] if asset["name"] == ASSET]
    require(len(assets) == 1, "Missing or ambiguous upstream XCFramework asset")
    asset = assets[0]
    digest = asset.get("digest", "")
    require(
        re.fullmatch(r"sha256:[0-9a-f]{64}", digest or "") is not None,
        "Upstream asset must supply a GitHub SHA-256 digest",
    )
    expected_url = (
        f"https://github.com/{config['upstream']}/releases/download/"
        f"{upstream['tag_name']}/{ASSET}"
    )
    require(asset["browser_download_url"] == expected_url, "Unexpected upstream URL")
    existing = subprocess.run(
        ["gh", "api", f"repos/{config['repository']}/releases/tags/{version}"],
        capture_output=True,
        text=True,
    )
    if existing.returncode:
        require(
            "HTTP 404" in existing.stderr,
            f"Cannot query destination release: {existing.stderr}",
        )
        needed = True
    else:
        needed = json.loads(existing.stdout)["draft"]
    data = {
        "upstream_tag": upstream["tag_name"],
        "version": version,
        "upstream_url": expected_url,
        "upstream_sha256": digest.split(":")[1],
        "repository": config["repository"],
        "needed": needed,
    }
    (BUILD / "release.json").write_text(json.dumps(data, indent=2) + "\n")
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a") as output:
            output.write(f"needed={str(needed).lower()}\nversion={version}\n")
    print(json.dumps(data, indent=2))


def validate_archive(archive):
    """Allow framework symlinks, but never paths or links escaping the archive root."""
    with zipfile.ZipFile(archive) as zipped:
        require(
            sum(item.file_size for item in zipped.infolist()) < 1024**3,
            "Archive exceeds 1 GiB unpacked limit",
        )
        for item in zipped.infolist():
            name = item.filename
            require(
                not name.startswith("/") and ".." not in Path(name).parts,
                "Unsafe archive path",
            )
            require(
                name.split("/")[0] in {"LookInsideServer.xcframework", "__MACOSX"},
                "Unexpected archive entry",
            )
            if stat.S_ISLNK(item.external_attr >> 16):
                target = zipped.read(item).decode()
                # Framework links only point down to Versions/Current or A. Disallow
                # parent traversal even when lexical normalization appears contained.
                require(".." not in Path(target).parts, "Unsafe framework symlink")
                resolved = posixpath.normpath(
                    posixpath.join(posixpath.dirname(name), target)
                )
                require(
                    not target.startswith("/")
                    and resolved.startswith("LookInsideServer.xcframework/"),
                    "Unsafe framework symlink",
                )


def podspec(metadata, digest):
    version = metadata["version"]
    repository = metadata["repository"]
    return f"""# Created by yuxilong on 2026/10/16.
# Generated by scripts/release.py; upstream binary retains its original authorship.
Pod::Spec.new do |s|
  s.name = 'LookInsideServer'
  s.version = '{version}'
  s.summary = 'LookInside Server with a local test CA.'
  s.homepage = 'https://github.com/{repository}'
  s.license = {{ :type => 'MIT' }}
  s.authors = {{ 'LookInside' => 'support@lookinside-app.com' }}
  s.source = {{ :http => 'https://github.com/{repository}/releases/download/{version}/{ASSET}',
               :sha256 => '{digest}' }}
  s.ios.deployment_target = '15.0'
  s.osx.deployment_target = '14.0'
  s.swift_versions = ['5.9']
  s.vendored_frameworks = 'LookInsideServer.xcframework'
  # The server starts from its load hooks even when the app references no symbols.
  s.user_target_xcconfig = {{ 'OTHER_LDFLAGS' => '$(inherited) -Wl,-needed_framework,LookInsideServer' }}
end
"""


def build(config):
    metadata = json.loads((BUILD / "release.json").read_text())
    # Metadata is generated locally by detect, never supplied by a workflow expression.
    require(
        metadata["version"]
        == release_version(metadata["upstream_tag"], config["patch_revision"]),
        "Release metadata/config mismatch",
    )
    require(metadata["repository"] == config["repository"], "Repository mismatch")
    archive = BUILD / "upstream.zip"
    if not archive.exists():
        run(
            "curl",
            "--fail",
            "--location",
            "--retry",
            "3",
            "--proto",
            "=https",
            "--proto-redir",
            "=https",
            "--output",
            str(archive),
            metadata["upstream_url"],
        )
    require(
        sha256(archive.read_bytes()) == metadata["upstream_sha256"],
        "Upstream ZIP digest mismatch",
    )
    validate_archive(archive)
    root_path = BASE / "certs/local-root.der"
    root = root_path.read_bytes()
    require(sha256(root) == config["local_root_sha256"], "Unexpected local CA")
    run(
        "openssl",
        "x509",
        "-inform",
        "DER",
        "-in",
        str(root_path),
        "-checkend",
        "0",
        "-noout",
    )
    text = run(
        "openssl", "x509", "-inform", "DER", "-in", str(root_path), "-text", "-noout"
    )
    require("CA:TRUE" in text, "Replacement certificate must be a CA")
    unpacked = BUILD / "unpacked"
    require(
        not unpacked.exists(),
        "Unpacked output already exists; use a fresh build directory",
    )
    run("ditto", "-x", "-k", str(archive), str(unpacked))
    framework = unpacked / "LookInsideServer.xcframework"
    info = plistlib.loads((framework / "Info.plist").read_bytes())
    libraries = info["AvailableLibraries"]
    require(libraries, "Empty XCFramework")
    report = {**metadata, "root_sha256": sha256(root), "libraries": []}
    seen = set()
    for library in libraries:
        identifier = library["LibraryIdentifier"]
        require(identifier not in seen, "Duplicate library identifier")
        seen.add(identifier)
        require(
            library["SupportedPlatform"] in {"ios", "macos"}, "Unsupported platform"
        )
        bundle = (framework / identifier / library["LibraryPath"]).resolve()
        require(
            bundle.is_relative_to(framework.resolve()), "Framework path escapes archive"
        )
        binary = (bundle / "LookInsideServer").resolve()
        require(binary.is_relative_to(bundle), "Binary path escapes framework")
        result = patch_binary(
            binary,
            root,
            config["upstream_root_sha256"],
            library["SupportedArchitectures"],
        )
        run("codesign", "--force", "--sign", "-", "--timestamp=none", str(bundle))
        run("codesign", "--verify", "--strict", "--all-architectures", str(bundle))
        result.update(
            {"identifier": identifier, "signed_sha256": verify_binary(binary, root)}
        )
        report["libraries"].append(result)
    output = BUILD / "release"
    output.mkdir()
    destination = output / ASSET
    run(
        "ditto",
        "-c",
        "-k",
        "--sequesterRsrc",
        "--keepParent",
        str(framework),
        str(destination),
    )
    digest = sha256(destination.read_bytes())
    report["asset_sha256"] = digest
    (output / "manifest.json").write_text(json.dumps(report, indent=2) + "\n")
    (output / "LookInsideServer.podspec").write_text(podspec(metadata, digest))
    (output / "SHA256SUMS").write_text(
        "".join(
            f"{sha256(path.read_bytes())}  {path.name}\n"
            for path in sorted(output.iterdir())
        )
    )
    (BUILD / "release-notes.md").write_text(
        f"Upstream: [{metadata['upstream_tag']}]({metadata['upstream_url']})\n\n"
        f"Local test CA SHA-256: `{sha256(root)}`\n\n"
        "All supplied slices patched and ad-hoc signed. No CA private key included. "
        "Original signature identity is not preserved. Use only in test projects.\n\n"
        "```ruby\n"
        "pod 'LookInsideServer', :podspec => "
        f"'https://github.com/{metadata['repository']}/releases/download/"
        f"{metadata['version']}/LookInsideServer.podspec', :configurations => ['Debug']\n"
        "```\n"
    )
    print(json.dumps(report, indent=2))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["detect", "build"])
    args = parser.parse_args()
    config = json.loads((BASE / "config.json").read_text())
    {"detect": detect, "build": build}[args.command](config)


if __name__ == "__main__":
    main()
